def generate_dataset(output_path: Path, target_size: int = 800):
    """Генерирует полный датасет"""
    print(f"🦉 Генерация датасета для fine-tuning Сорена")
    print(f"   Целевой размер: {target_size} примеров")
    print()

    all_examples = []

    blocks = [
        ("Приветствия", generate_greetings, 100),
        ("Философия", generate_philosophy, 200),
        ("Эмоциональные триггеры", generate_emotional_triggers, 150),
        ("Вопросы о мире", generate_world_questions, 150),
        ("Советы", generate_advice, 150),
        ("Технические аналогии", generate_technical, 100),
        ("Запретные темы", generate_forbidden, 50),
    ]

    for name, generator, expected in blocks:
        print(f"📦 Блок '{name}' ({expected} примеров)...")
        examples = generator()
        print(f"   Сгенерировано: {len(examples)}")
        all_examples.extend(examples)

    # Перемешиваем
    random.shuffle(all_examples)

    # Обрезаем до целевого размера
    all_examples = all_examples[:target_size]

    # Сохраняем
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        for ex in all_examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")

    print()
    print(f"✅ Датасет сохранён: {output_path}")
    print(f"   Всего примеров: {len(all_examples)}")
    print(f"   Размер файла: {output_path.stat().st_size / 1024:.1f} KB")

    return all_examples


def main():
    parser = argparse.ArgumentParser(description="Подготовка датасета для fine-tuning Сорена")
    parser.add_argument("--output", default="./datasets/final_800.jsonl", help="Путь для сохранения")
    parser.add_argument("--size", type=int, default=800, help="Целевой размер датасета")

    args = parser.parse_args()
    generate_dataset(Path(args.output), args.size)


if __name__ == "__main__":
    main()