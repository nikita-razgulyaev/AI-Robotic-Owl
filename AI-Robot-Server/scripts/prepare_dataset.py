    emotions = {
        "calm": "",
        "loving": "Ты знаешь, я всегда рад тебя видеть. ",
        "tired": "*(лёгкая пауза)* Прости, сегодня ночь была долгой. ",
    }

    for user_msg, soren_resp in greetings[:5]:
        for emo, prefix in emotions.items():
            results.append({
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT + f"\n\n[Текущая эмоция: {emo}]"},
                    {"role": "user", "content": user_msg},
                    {"role": "assistant", "content": prefix + soren_resp}
                ]
            })

    return results[:100]


